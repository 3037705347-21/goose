package rollout

import (
	"context"
	"errors"
	"fmt"

	"github.com/google/uuid"
)

// Runner reconciles a manifest against a ledger and the target databases.
type Runner struct {
	m       *Manifest
	ledger  *Ledger
	factory ExecutorFactory
	runID   string

	// execs caches executors created during the current run.
	execs map[string]Executor
}

// Option configures a [Runner].
type Option func(*Runner)

// WithExecutorFactory injects a custom [ExecutorFactory]. By default the
// runner builds goose-backed executors from the manifest.
func WithExecutorFactory(f ExecutorFactory) Option {
	return func(r *Runner) {
		if f != nil {
			r.factory = f
		}
	}
}

// WithRunID pins the run identifier recorded in ledger entries. It is mainly
// useful for deterministic tests; a random UUID is generated by default.
func WithRunID(id string) Option {
	return func(r *Runner) {
		if id != "" {
			r.runID = id
		}
	}
}

// NewRunner returns a Runner for the given manifest and ledger.
func NewRunner(m *Manifest, ledger *Ledger, opts ...Option) *Runner {
	r := &Runner{
		m:       m,
		ledger:  ledger,
		factory: NewExecutorFactory(m.MigrationsDir, nil),
		runID:   uuid.NewString(),
		execs:   make(map[string]Executor),
	}
	for _, opt := range opts {
		opt(r)
	}
	return r
}

// RunID returns the identifier of the current (or last) run.
func (r *Runner) RunID() string { return r.runID }

// Run reconciles and advances the rollout.
//
// Generations are processed in manifest order. If any target fails or drifts,
// every target already upgraded in that generation is rolled back to its
// baseline and Run returns a non-nil error along with the partial report.
// Conflicts and failed rollbacks are sticky: subsequent runs report them and
// make no changes until a human intervenes.
func (r *Runner) Run(ctx context.Context) (*Report, error) {
	if err := r.ledger.Lock(); err != nil {
		return newReport(r.runID), err
	}
	defer func() { _ = r.ledger.Unlock() }()
	defer r.closeExecutors()

	report := newReport(r.runID)

	for gi := range r.m.Generations {
		g := &r.m.Generations[gi]
		state, err := r.ledger.Generation(gi)
		if err != nil {
			return report, err
		}

		switch state.Status {
		case GenSucceeded:
			report.Generations = append(report.Generations, genReportFromState(state))
			continue
		case GenFailed:
			report.Generations = append(report.Generations, genReportFromState(state))
			return report, fmt.Errorf("generation %q previously failed (%s); manual intervention required",
				g.Name, state.Detail)
		case GenPending, GenInProgress, GenRolledBack:
			// process below
		default:
			return report, fmt.Errorf("generation %q: unknown status %q", g.Name, state.Status)
		}

		// Sticky entries (unresolved conflict / rollback_failed) block without
		// touching any database.
		if reason, sticky := r.stickyReason(gi); sticky {
			gr := genReportFromState(state)
			gr.Detail = reason
			report.Generations = append(report.Generations, gr)
			return report, fmt.Errorf("generation %q blocked: %s", g.Name, reason)
		}

		if err := r.ledger.StartGeneration(gi); err != nil {
			return report, err
		}

		// A generation that already contains abort signals (a failed or
		// conflicted target, a rollback intent, or closed rolled_back entries)
		// is resumed through the dedicated recovery flow: converge intents and
		// return every upgraded target to its baseline.
		if r.hasAbortSignal(gi) {
			gr, hard, reason, crash := r.recoverGeneration(ctx, gi, g)
			if crash {
				gr.Index = gi
				gr.Name = g.Name
				gr.TargetVersion = g.TargetVersion
				report.Generations = append(report.Generations, gr)
				return report, fmt.Errorf("generation %q: %w", g.Name, ErrSimulatedCrash)
			}
			finalStatus := GenRolledBack
			if hard {
				finalStatus = GenFailed
			}
			if err := r.ledger.FinishGeneration(gi, finalStatus, reason); err != nil {
				return report, err
			}
			gr.Status = finalStatus
			report.Generations = append(report.Generations, gr)
			return report, fmt.Errorf("generation %q failed: %s", g.Name, reason)
		}

		gr := &GenReport{
			Index:         gi,
			Name:          g.Name,
			TargetVersion: g.TargetVersion,
		}
		abortReason, crash := r.processGeneration(ctx, gi, g, gr)
		if crash {
			report.Generations = append(report.Generations, *gr)
			return report, fmt.Errorf("generation %q: %w", g.Name, ErrSimulatedCrash)
		}
		if abortReason == "" {
			if err := r.ledger.FinishGeneration(gi, GenSucceeded, ""); err != nil {
				return report, err
			}
			gr.Status = GenSucceeded
			report.Generations = append(report.Generations, *gr)
			continue
		}

		// The generation aborted (upgrade failure or drift). Recover: roll back
		// every target currently upgraded.
		recoverGr, hard, recoveryReason, recoveryCrash := r.recoverGeneration(ctx, gi, g)
		if recoveryCrash {
			recoverGr.Index = gi
			recoverGr.Name = g.Name
			recoverGr.TargetVersion = g.TargetVersion
			recoverGr.Targets = reconcileTargetReports(g, gr.Targets, recoverGr.Targets)
			report.Generations = append(report.Generations, recoverGr)
			return report, fmt.Errorf("generation %q: %w", g.Name, ErrSimulatedCrash)
		}
		// Per target, prefer the recovery report (later truth); fall back to the
		// pre-abort report when recovery did not touch the target.
		recoverGr.Index = gi
		recoverGr.Name = g.Name
		recoverGr.TargetVersion = g.TargetVersion
		recoverGr.Targets = reconcileTargetReports(g, gr.Targets, recoverGr.Targets)

		finalStatus := GenRolledBack
		if hard {
			finalStatus = GenFailed
		}
		if err := r.ledger.FinishGeneration(gi, finalStatus, abortReason); err != nil {
			return report, err
		}
		recoverGr.Status = finalStatus
		recoverGr.Detail = abortReason
		report.Generations = append(report.Generations, recoverGr)

		_ = recoveryReason
		return report, fmt.Errorf("generation %q failed: %s", g.Name, abortReason)
	}
	return report, nil
}

// processGeneration runs the normal, forward-only flow for one generation. It
// returns a non-empty abort reason when a target fails or drifts.
func (r *Runner) processGeneration(
	ctx context.Context,
	gi int,
	g *Generation,
	gr *GenReport,
) string {
	for _, name := range g.Targets {
		exec, err := r.executor(ctx, name)
		if err != nil {
			gr.Targets = append(gr.Targets, failedReport(name, g.TargetVersion, err.Error()))
			return err.Error()
		}

		// An open upgrading intent from a crashed run: converge against the
		// observed state before doing anything else.
		if intent, ok := r.ledger.OpenIntent(name); ok && intent.GenIndex == gi && intent.Kind == IntentUpgrading {
			observed, err := exec.CurrentVersion(ctx)
			if err != nil {
				gr.Targets = append(gr.Targets, failedReport(name, g.TargetVersion, err.Error()))
				return err.Error()
			}
			switch {
			case observed == intent.To:
				if entryErr := r.ledger.AppendEntry(upgradedEntry(r.runID, gi, g.Name, intent, observed)); entryErr != nil {
					return entryErr.Error()
				}
				gr.Targets = append(gr.Targets,
					upgradedReport(name, g.TargetVersion, intent, observed))
				continue
			case observed == intent.From:
				// Nothing was applied: reuse the open intent and run the
				// upgrade directly instead of appending a duplicate intent.
				if err := exec.UpgradeTo(ctx, intent.To); err != nil {
					failedObserved, _ := exec.CurrentVersion(ctx)
					fe := failedEntry(r.runID, gi, g.Name, intent, err.Error())
					fe.Observed = failedObserved
					_ = r.ledger.AppendEntry(fe)
					fr := failedReportWithBaseline(name, g.TargetVersion, intent.Baseline, err.Error())
					fr.Observed = failedObserved
					gr.Targets = append(gr.Targets, fr)
					return err.Error()
				}
				newObserved, err := exec.CurrentVersion(ctx)
				if err != nil {
					return err.Error()
				}
				if entryErr := r.ledger.AppendEntry(upgradedEntry(r.runID, gi, g.Name, intent, newObserved)); entryErr != nil {
					return entryErr.Error()
				}
				gr.Targets = append(gr.Targets,
					upgradedReport(name, g.TargetVersion, intent, newObserved))
				continue
			default:
				detail := fmt.Sprintf("manual drift during upgrade: expected %d or %d, database reports %d",
					intent.To, intent.From, observed)
				_ = r.ledger.AppendEntry(conflictEntry(r.runID, gi, g.Name, intent, intent.From, observed, detail))
				gr.Targets = append(gr.Targets, conflictReport(name, g.TargetVersion, intent.Baseline, intent.From, observed, detail))
				return detail
			}
		}

		observed, err := exec.CurrentVersion(ctx)
		if err != nil {
			gr.Targets = append(gr.Targets, failedReport(name, g.TargetVersion, err.Error()))
			return err.Error()
		}

		// First time this target is seen anywhere: adopt its observed version
		// as the per-generation baseline.
		last, hasLast := r.ledger.LastEntry(name)
		baseline := observed
		if !hasLast {
			e := Entry{
				RunID: r.runID, GenIndex: gi, GenName: g.Name, Target: name,
				Kind: EntryAdopted, Baseline: observed, Observed: observed,
			}
			if err := r.ledger.AppendEntry(e); err != nil {
				return err.Error()
			}
		} else {
			baseline = baselineBefore(gi, name, r.ledger, last)
		}

		recorded := observed
		if hasLast {
			recorded = RecordedVersion(last)
		}
		if observed != recorded {
			detail := fmt.Sprintf("manual drift: ledger records version %d but database reports %d", recorded, observed)
			e := conflictEntry(r.runID, gi, g.Name,
				Entry{Target: name, Baseline: baseline}, recorded, observed, detail)
			if err := r.ledger.AppendEntry(e); err != nil {
				return err.Error()
			}
			gr.Targets = append(gr.Targets,
				conflictReport(name, g.TargetVersion, baseline, recorded, observed, detail))
			return detail
		}

		if observed >= g.TargetVersion {
			e := Entry{
				RunID: r.runID, GenIndex: gi, GenName: g.Name, Target: name,
				Kind: EntrySkipped, Baseline: baseline, Observed: observed,
			}
			if err := r.ledger.AppendEntry(e); err != nil {
				return err.Error()
			}
			gr.Targets = append(gr.Targets, TargetReport{
				Name: name, Desired: g.TargetVersion,
				Recorded: recorded, Observed: observed,
				Outcome: EntrySkipped, Baseline: baseline,
			})
			continue
		}

		// Upgrade: persist intent, act, persist result.
		intent := Entry{
			RunID: r.runID, GenIndex: gi, GenName: g.Name, Target: name,
			Kind: IntentUpgrading, Baseline: baseline,
			From: observed, To: g.TargetVersion, Observed: observed,
		}
		if err := r.ledger.AppendEntry(intent); err != nil {
			return err.Error()
		}
		if err := exec.UpgradeTo(ctx, g.TargetVersion); err != nil {
			failedObserved, _ := exec.CurrentVersion(ctx)
			fe := failedEntry(r.runID, gi, g.Name, intent, err.Error())
			fe.Observed = failedObserved
			_ = r.ledger.AppendEntry(fe)
			fr := failedReportWithBaseline(name, g.TargetVersion, baseline, err.Error())
			fr.Observed = failedObserved
			gr.Targets = append(gr.Targets, fr)
			return err.Error()
		}
		newObserved, err := exec.CurrentVersion(ctx)
		if err != nil {
			return err.Error()
		}
		if err := r.ledger.AppendEntry(upgradedEntry(r.runID, gi, g.Name, intent, newObserved)); err != nil {
			return err.Error()
		}
		gr.Targets = append(gr.Targets,
			upgradedReport(name, g.TargetVersion, intent, newObserved))
	}
	return ""
}

// recoverGeneration converges a generation that already aborted. It ensures
// every target currently upgraded is returned to its baseline. hard is true
// when recovery cannot complete (rollback failure or mid-rollback drift).
func (r *Runner) recoverGeneration(
	ctx context.Context,
	gi int,
	g *Generation,
) (GenReport, bool, string) {
	gr := GenReport{Targets: []TargetReport{}}
	hard := false
	reason := "generation aborted; recovery converged"

	for _, name := range g.Targets {
		latest := latestGenEntry(r.ledger, gi, name)

		switch latest.Kind {
		case EntryRollbackFailed:
			// Sticky hard failure: do not touch the database.
			hard = true
			reason = latest.Detail
			gr.Targets = append(gr.Targets, TargetReport{
				Name: name, Desired: g.TargetVersion,
				Outcome: latest.Kind, Detail: latest.Detail,
			})
			continue
		case EntryConflict:
			// Sticky conflict: leave the database alone. It does not make the
			// rollback of other targets a hard failure; the next run is blocked
			// by the sticky check regardless of generation status.
			gr.Targets = append(gr.Targets, TargetReport{
				Name: name, Desired: g.TargetVersion,
				Recorded: latest.Expected, Observed: latest.Observed,
				Outcome: EntryConflict, Baseline: latest.Baseline, Detail: latest.Detail,
			})
			continue

		case EntryAdopted, EntrySkipped, "":
			// Nothing was applied; nothing to roll back.
			if latest.Kind != "" {
				gr.Targets = append(gr.Targets, TargetReport{
					Name: name, Desired: g.TargetVersion,
					Observed: latest.Observed, Outcome: latest.Kind,
					Baseline: latest.Baseline, Detail: latest.Detail,
				})
			}
			continue
		case EntryFailed:
			// The upgrade may have applied one or more versions before failing.
			// Judge by the observed version: anything above baseline must be
			// rolled back.
			exec, execErr := r.executor(ctx, name)
			if execErr != nil {
				hard = true
				gr.Targets = append(gr.Targets, TargetReport{
					Name: name, Desired: g.TargetVersion,
					Outcome: EntryRollbackFailed, Detail: execErr.Error(),
				})
				continue
			}
			failedObserved, obsErr := exec.CurrentVersion(ctx)
			if obsErr != nil {
				hard = true
				continue
			}
			if failedObserved <= latest.Baseline {
				gr.Targets = append(gr.Targets, TargetReport{
					Name: name, Desired: g.TargetVersion,
					Observed: failedObserved, Outcome: EntryFailed,
					Baseline: latest.Baseline, Detail: latest.Detail,
				})
				continue
			}
			tr, hardFail := r.downgradeToBaseline(ctx, gi, g, name, latest.Baseline, failedObserved)
			gr.Targets = append(gr.Targets, tr)
			if hardFail {
				hard = true
			}
			continue

		case EntryUpgraded, IntentUpgrading, IntentRollingBack, EntryRolledBack:
			// converge below
		}

		exec, err := r.executor(ctx, name)
		if err != nil {
			hard = true
			gr.Targets = append(gr.Targets, TargetReport{
				Name: name, Desired: g.TargetVersion,
				Outcome: EntryRollbackFailed, Detail: err.Error(),
			})
			continue
		}

		baseline := latest.Baseline
		observed, err := exec.CurrentVersion(ctx)
		if err != nil {
			hard = true
			continue
		}

		// Resolve an open upgrading intent first.
		if latest.Kind == IntentUpgrading {
			switch {
			case observed == latest.To:
				if err := r.ledger.AppendEntry(upgradedEntry(r.runID, gi, g.Name, latest, observed)); err != nil {
					hard = true
					continue
				}
			case observed == latest.From:
				// Upgrade never happened: nothing to roll back.
				gr.Targets = append(gr.Targets, TargetReport{
					Name: name, Desired: g.TargetVersion, Observed: observed,
					Outcome: EntryFailed, Baseline: baseline,
				})
				continue
			default:
				detail := fmt.Sprintf("manual drift during upgrade: expected %d or %d, database reports %d",
					latest.To, latest.From, observed)
				_ = r.ledger.AppendEntry(conflictEntry(r.runID, gi, g.Name, latest, latest.From, observed, detail))
				gr.Targets = append(gr.Targets, TargetReport{
					Name: name, Desired: g.TargetVersion,
					Recorded: latest.From, Observed: observed,
					Outcome: EntryConflict, Baseline: baseline, Detail: detail,
				})
				continue
			}
		}

		// Resolve an open rolling_back intent.
		if latest.Kind == IntentRollingBack {
			switch {
			case observed == latest.To:
				if err := r.ledger.AppendEntry(rolledBackEntry(r.runID, gi, g.Name, latest, observed)); err != nil {
					hard = true
					continue
				}
				gr.Targets = append(gr.Targets, TargetReport{
					Name: name, Desired: g.TargetVersion, Observed: observed,
					Outcome: EntryRolledBack, Baseline: baseline,
				})
				continue
			case observed != latest.From:
				detail := fmt.Sprintf("manual drift during rollback: expected %d or %d, database reports %d",
					latest.To, latest.From, observed)
				_ = r.ledger.AppendEntry(Entry{
					RunID: r.runID, GenIndex: gi, GenName: g.Name, Target: name,
					Kind: EntryRollbackFailed, Baseline: baseline,
					From: latest.From, To: latest.To, Observed: observed, Detail: detail,
				})
				hard = true
				gr.Targets = append(gr.Targets, TargetReport{
					Name: name, Desired: g.TargetVersion,
					Recorded: latest.From, Observed: observed,
					Outcome: EntryRollbackFailed, Baseline: baseline, Detail: detail,
				})
				continue
			}
		}

		// Closed upgraded entry (or a rolling_back intent observed still at
		// From): downgrade must run. Re-read current state in case the
		// upgrading-intent resolution above changed it.
		observed, err = exec.CurrentVersion(ctx)
		if err != nil {
			hard = true
			continue
		}
		if observed <= baseline {
			if err := r.ledger.AppendEntry(rolledBackEntry(r.runID, gi, g.Name,
				Entry{Target: name, Baseline: baseline, From: observed, To: baseline}, observed)); err != nil {
				hard = true
				continue
			}
			gr.Targets = append(gr.Targets, TargetReport{
				Name: name, Desired: g.TargetVersion, Observed: observed,
				Outcome: EntryRolledBack, Baseline: baseline,
			})
			continue
		}

		// Persist (or reuse) the rolling_back intent, then downgrade.
		tr, hardFail := r.downgradeToBaseline(ctx, gi, g, name, baseline, observed)
		gr.Targets = append(gr.Targets, tr)
		if hardFail {
			hard = true
		}
	}

	return gr, hard, reason
}

// downgradeToBaseline persists a rolling_back intent (reusing an open one),
// downgrades the target to baseline, and records the closed result. It returns
// the target report and whether recovery failed (hard).
func (r *Runner) downgradeToBaseline(
	ctx context.Context,
	gi int,
	g *Generation,
	name string,
	baseline, from int64,
) (TargetReport, bool) {
	exec, err := r.executor(ctx, name)
	if err != nil {
		return TargetReport{
			Name: name, Desired: g.TargetVersion,
			Outcome: EntryRollbackFailed, Detail: err.Error(),
		}, true
	}
	if intent, ok := r.ledger.OpenIntent(name); !(ok && intent.GenIndex == gi && intent.Kind == IntentRollingBack) {
		intent := Entry{
			RunID: r.runID, GenIndex: gi, GenName: g.Name, Target: name,
			Kind: IntentRollingBack, Baseline: baseline,
			From: from, To: baseline,
		}
		if err := r.ledger.AppendEntry(intent); err != nil {
			return TargetReport{
				Name: name, Desired: g.TargetVersion,
				Outcome: EntryRollbackFailed, Detail: err.Error(),
			}, true
		}
	}
	if err := exec.DowngradeTo(ctx, baseline); err != nil {
		_ = r.ledger.AppendEntry(Entry{
			RunID: r.runID, GenIndex: gi, GenName: g.Name, Target: name,
			Kind: EntryRollbackFailed, Baseline: baseline,
			From: from, To: baseline, Detail: err.Error(),
		})
		return TargetReport{
			Name: name, Desired: g.TargetVersion, Observed: from,
			Outcome: EntryRollbackFailed, Baseline: baseline, Detail: err.Error(),
		}, true
	}
	finalObserved, err := exec.CurrentVersion(ctx)
	if err != nil {
		return TargetReport{
			Name: name, Desired: g.TargetVersion,
			Outcome: EntryRollbackFailed, Detail: err.Error(),
		}, true
	}
	if err := r.ledger.AppendEntry(rolledBackEntry(r.runID, gi, g.Name,
		Entry{Target: name, Baseline: baseline, From: from, To: baseline}, finalObserved)); err != nil {
		return TargetReport{
			Name: name, Desired: g.TargetVersion,
			Outcome: EntryRollbackFailed, Detail: err.Error(),
		}, true
	}
	return TargetReport{
		Name: name, Desired: g.TargetVersion, Observed: finalObserved,
		Outcome: EntryRolledBack, Baseline: baseline,
	}, false
}

// hasAbortSignal reports whether generation gi already contains evidence that
// it aborted previously (failed/conflict/rolled_back/rollback_failed entry, or
// a rolling_back intent).
func (r *Runner) hasAbortSignal(gi int) bool {
	for _, e := range r.ledger.GenEntries(gi) {
		switch e.Kind {
		case EntryFailed, EntryConflict, EntryRolledBack, EntryRollbackFailed, IntentRollingBack:
			return true
		}
	}
	return false
}

// stickyReason scans generation gi for unresolved conflict or rollback_failed
// entries and returns a human-readable reason.
func (r *Runner) stickyReason(gi int) (string, bool) {
	var reason string
	sticky := false
	for _, e := range r.ledger.GenEntries(gi) {
		switch e.Kind {
		case EntryConflict, EntryRollbackFailed:
			reason = e.Detail
			sticky = true
		}
	}
	return reason, sticky
}

func (r *Runner) executor(ctx context.Context, name string) (Executor, error) {
	if e, ok := r.execs[name]; ok {
		return e, nil
	}
	t, ok := r.m.Target(name)
	if !ok {
		return nil, fmt.Errorf("unknown target %q", name)
	}
	e, err := r.factory(ctx, t)
	if err != nil {
		return nil, err
	}
	r.execs[name] = e
	return e, nil
}

func (r *Runner) closeExecutors() {
	for name, e := range r.execs {
		_ = e.Close()
		delete(r.execs, name)
	}
}

// baselineBefore returns the version recorded immediately before generation gi
// started for target, falling back to the target's last entry.
func baselineBefore(gi int, name string, l *Ledger, last Entry) int64 {
	if last.Kind.IsIntent() {
		return last.Baseline
	}
	for _, e := range l.Entries() {
		if e.Target == name && e.GenIndex < gi {
			return RecordedVersion(e)
		}
	}
	return RecordedVersion(last)
}

func latestGenEntry(l *Ledger, gi int, name string) Entry {
	var latest Entry
	found := false
	for _, e := range l.GenEntries(gi) {
		if e.Target == name {
			latest = e
			found = true
		}
	}
	if !found {
		return Entry{}
	}
	return latest
}

// reconcileTargetReports combines pre-abort and recovery reports in manifest
// target order. The recovery (post) report is preferred when present, since it
// reflects the final state; otherwise the pre-abort report is kept.
func reconcileTargetReports(g *Generation, pre, post []TargetReport) []TargetReport {
	postByTarget := map[string]TargetReport{}
	for _, tr := range post {
		postByTarget[tr.Name] = tr
	}
	preByTarget := map[string]TargetReport{}
	for _, tr := range pre {
		preByTarget[tr.Name] = tr
	}
	out := make([]TargetReport, 0, len(g.Targets))
	for _, name := range g.Targets {
		if tr, ok := postByTarget[name]; ok {
			out = append(out, tr)
		} else if tr, ok := preByTarget[name]; ok {
			out = append(out, tr)
		}
	}
	return out
}

// ErrAborted is returned (wrapped) when a generation aborts for a reason other
// than a direct migration error.
var ErrAborted = errors.New("rollout aborted")
